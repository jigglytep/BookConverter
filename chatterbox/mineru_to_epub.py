def natural_sort_key(path: Path):
    """Sort paths containing numbers in human/natural order (e.g., page_2 before page_10)."""
    return [int(text) if text.isdigit() else text.lower() for text in re.split(r"(\d+)", path.name)]


def read_file_text(path: Path) -> str:
    """Reads a text file with multiple encoding fallbacks (utf-8, utf-8-sig, cp1252, latin-1)."""
    for encoding in ("utf-8", "utf-8-sig", "cp1252", "latin-1"):
        try:
            return path.read_text(encoding=encoding)
        except (UnicodeDecodeError, LookupError):
            continue
    return path.read_text(encoding="utf-8", errors="replace")


def extract_page_number(path: Path, fallback_idx: int = 1) -> int:
    """Extract 1-based page number from filename like '..._page_0012.md' or 'page_12.txt'."""
    m = re.search(r"page[_-]?(\d+)", path.stem, re.IGNORECASE)
    if m:
        return int(m.group(1))
    nums = re.findall(r"\d+", path.stem)
    if nums:
        return int(nums[-1])
    return fallback_idx


def format_page_num_str(page_num: int, pad_width: int = 4) -> str:
    """Format page number for filenames (e.g., 0012)."""
    return f"{page_num:0{pad_width}d}"


def format_smil_timestamp(seconds: float) -> str:
    """Format duration in seconds into strict HH:MM:SS.mmm format."""
    total_ms = max(0, int(round(seconds * 1000.0)))
    hours, rem_ms = divmod(total_ms, 3600 * 1000)
    minutes, rem_ms = divmod(rem_ms, 60 * 1000)
    secs, ms = divmod(rem_ms, 1000)
    return f"{hours:02d}:{minutes:02d}:{secs:02d}.{ms:03d}"


def format_page_chapter_title(page_num: int, toc_map: Optional[Dict[int, str]] = None) -> str:
    """
    Format page chapter title per specification:
    - Default Chapter Title: 'Page {page_number}'
    - TOC Match Chapter Title: 'Page {page_number}: {title of page in table of contents}'
    """
    if toc_map and page_num in toc_map:
        toc_title = toc_map[page_num].strip()
        if toc_title:
            return f"Page {page_num}: {toc_title}"
    return f"Page {page_num}"


def _clean_toc_heading(raw_title: str) -> str:
    """Clean markdown, HTML tags, and trailing page numbers/dots from a TOC heading."""
    s = re.sub(r"<[^>]+>", "", raw_title)
    s = html.unescape(s)
    s = re.sub(r"^#+\s*", "", s).strip()
    s = re.sub(r"[\*`_~]+", "", s).strip()
    # Strip trailing dot leaders and page numbers e.g. ". . . 12"
    s = re.sub(r"(?:\s*\.\s*){2,}\d+\s*$", "", s).strip()
    s = re.sub(r"\s+", " ", s).strip()
    return s


def _add_toc_entry(toc_lists: Dict[int, List[str]], page_num: int, title: str):
    cleaned = _clean_toc_heading(title)
    if not cleaned or len(cleaned) < 2:
        return
    if cleaned.lower() in ("my bookmarks", "frontcover", "body"):
        return
    existing = toc_lists.setdefault(page_num, [])
    norm_cleaned = re.sub(r"[^a-z0-9]+", "", cleaned.lower())
    for item in existing:
        norm_item = re.sub(r"[^a-z0-9]+", "", item.lower())
        if norm_item == norm_cleaned or (norm_cleaned and (norm_cleaned in norm_item or norm_item in norm_cleaned)):
            return
    existing.append(cleaned)


def canonical_book_name(path: Path) -> str:
    """Derive canonical book name from a folder or file path."""
    name = path.stem if path.is_file() else path.name
    for suffix in ("_txt", "_md", "_pages"):
        if name.endswith(suffix):
            return name[: -len(suffix)]
    m = re.match(r"^(.+)_page_\d+$", name, re.IGNORECASE)
    if m:
        return m.group(1)
    return name


def find_companion_markdown_dir(input_path: Path) -> Optional[Path]:
    """Locate the rich MinerU Markdown directory corresponding to a _txt directory if available."""
    if input_path.is_dir():
        md_files = list(input_path.glob("*.md"))
        if md_files:
            return input_path
    bname = canonical_book_name(input_path)
    candidates = [
        input_path.parent / f"{bname}_md",
        ROOT_DIR / "TTS_Script" / "completed" / f"{bname}_md",
        ROOT_DIR / "mineru" / "out" / f"{bname}_md",
        ROOT_DIR / "mineru" / "completed" / f"{bname}_md",
        ROOT_DIR / "completed" / f"{bname}_md",
    ]
    for cand in candidates:
        if cand.is_dir() and any(cand.glob("*.md")):
            return cand.resolve()
    return None


def find_companion_pdf(input_path: Path) -> Optional[Path]:
    """Locate the original source PDF for a book if available in workspace folders."""
    bname = canonical_book_name(input_path)
    search_dirs = [
        input_path if input_path.is_dir() else input_path.parent,
        input_path.parent,
        ROOT_DIR / "mineru" / "completed",
        ROOT_DIR / "completed",
        ROOT_DIR / "mineru" / "in",
        ROOT_DIR / "in",
        ROOT_DIR / "PDF",
    ]
    for sdir in search_dirs:
        if not sdir.is_dir():
            continue
        for ext in (".pdf", ".PDF"):
            cand = sdir / f"{bname}{ext}"
            if cand.is_file() and cand.stat().st_size > 0:
                return cand.resolve()
    return None


def load_or_extract_book_metadata(
    input_path: Path,
    md_dir: Optional[Path] = None,
    pdf_path: Optional[Path] = None,
) -> dict:
    """
    Load Stage 1 `book_metadata.json` from `input_path` or `md_dir` if present;
    if missing (e.g. backlog book), automatically run `metadata_extractor.extract_book_metadata`
    on-the-fly using the companion Markdown folder and source PDF.
    """
    input_p = Path(input_path).resolve()
    if md_dir is None:
        md_dir = find_companion_markdown_dir(input_p)
    if pdf_path is None:
        pdf_path = find_companion_pdf(md_dir or input_p)

    search_dirs: List[Path] = []
    if input_p.is_dir():
        search_dirs.append(input_p)
    if md_dir and md_dir.is_dir() and md_dir not in search_dirs:
        search_dirs.append(md_dir)

    meta: Optional[dict] = None
    for sdir in search_dirs:
        cand = sdir / "book_metadata.json"
        if cand.is_file():
            try:
                meta = json.loads(cand.read_text(encoding="utf-8"))
                break
            except Exception as e:
                logger.warning("Failed reading %s: %s", cand, e)

    if meta is None and metadata_extractor is not None:
        target_scan_dir = md_dir if (md_dir and md_dir.is_dir()) else (input_p if input_p.is_dir() else input_p.parent)
        out_dir = input_p if input_p.is_dir() else target_scan_dir
        try:
            meta = metadata_extractor.extract_book_metadata(
                pdf_path=pdf_path,
                md_dir=target_scan_dir,
                book_stem=canonical_book_name(input_p),
                output_dir=out_dir,
                extract_cover=True,
            )
            # Also save in md_dir if different from out_dir
            if md_dir and md_dir.is_dir() and md_dir != out_dir:
                try:
                    (md_dir / "book_metadata.json").write_text(
                        json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8"
                    )
                except Exception:
                    pass
        except Exception as e:
            logger.warning("Fallback metadata extraction failed for %s: %s", input_p, e)

    if meta is None:
        bname = canonical_book_name(input_p)
        meta = {
            "canonicalBookName": bname,
            "title": bname,
            "subtitle": None,
            "authors": [],
            "narrators": [],
            "series": [],
            "genres": [],
            "publishedYear": None,
            "publishedDate": None,
            "publisher": None,
            "description": None,
            "isbn": None,
            "asin": None,
            "language": "en",
            "explicit": False,
            "abridged": False,
            "tags": ["TTS", "MinerU"],
            "sourcePdf": str(pdf_path) if pdf_path else None,
            "coverPath": None,
        }

    # Resolve or extract cover.jpg if missing
    cover_path: Optional[Path] = None
    if meta.get("coverPath") and Path(meta["coverPath"]).is_file():
        cover_path = Path(meta["coverPath"]).resolve()
    else:
        for sdir in search_dirs:
            cand_cov = sdir / "cover.jpg"
            if cand_cov.is_file() and cand_cov.stat().st_size > 1024:
                cover_path = cand_cov.resolve()
                break
        if cover_path is None and pdf_path and pdf_path.is_file() and metadata_extractor is not None:
            target_cov_dir = search_dirs[0] if search_dirs else input_p.parent
            cover_path = metadata_extractor.extract_pdf_cover(pdf_path, target_cov_dir / "cover.jpg")

    if cover_path:
        meta["coverPath"] = str(cover_path)
    if pdf_path and not meta.get("sourcePdf"):
        meta["sourcePdf"] = str(pdf_path)

    return meta


def _extract_pdf_outline_toc(pdf_path: Path) -> Dict[int, List[str]]:
    """Extract PDF bookmark/outline page->titles mapping using pdftohtml -xml."""
    toc_lists: Dict[int, List[str]] = {}
    if not pdf_path or not pdf_path.is_file() or shutil.which("pdftohtml") is None:
        return toc_lists
    try:
        res = subprocess.run(
            ["pdftohtml", "-xml", "-i", "-f", "1", "-l", "1", "-stdout", str(pdf_path)],
            capture_output=True,
            text=True,
            timeout=15,
        )
        if "<outline>" in res.stdout and "</outline>" in res.stdout:
            outline_block = res.stdout.split("<outline>", 1)[1].rsplit("</outline>", 1)[0]
            for m in re.finditer(r'<item\s+page="(\d+)">(.*?)</item>', outline_block, re.DOTALL):
                pg = int(m.group(1))
                title = html.unescape(re.sub(r"<[^>]+>", "", m.group(2))).strip()
                _add_toc_entry(toc_lists, pg, title)
    except Exception as e:
        logger.debug("PDF outline extraction skipped for %s: %s", pdf_path, e)
    return toc_lists


def _extract_markdown_toc_and_headings(doc_files: List[Path]) -> Dict[int, List[str]]:
    """
    Extract TOC mapping from Markdown/Text page files by:
    1. Parsing any explicit 'Table of Contents' / 'Contents' pages and matching titles/page numbers.
    2. Inspecting page headings (#, ##, and standard chapter/roman-numeral headings).
    """
    toc_lists: Dict[int, List[str]] = {}
    page_texts: Dict[int, str] = {}
    page_headings: Dict[int, List[str]] = {}

    for idx, f in enumerate(doc_files, 1):
        pnum = extract_page_number(f, idx)
        txt = read_file_text(f)
        page_texts[pnum] = txt

        # Extract candidate headings on this page
        for line in txt.splitlines():
            s = line.strip()
            if not s or s.startswith("<!--"):
                continue
            m_h = re.match(r"^(#{1,2})\s+(.+)$", s)
            if m_h:
                level = len(m_h.group(1))
                h_text = _clean_toc_heading(m_h.group(2))
                if not h_text:
                    continue
                # Avoid treating long prose sentences accidentally tagged as ## by OCR as TOC titles
                words = h_text.split()
                is_structural = bool(COMPILED_DEFAULT_CHAPTER_REGEX.match(h_text))
                if level == 1 or is_structural or (len(words) <= 10 and not h_text.endswith((".", "?", "!"))):
                    page_headings.setdefault(pnum, []).append(h_text)
            elif COMPILED_DEFAULT_CHAPTER_REGEX.match(s):
                h_text = _clean_toc_heading(s)
                if h_text and len(h_text.split()) <= 12:
                    page_headings.setdefault(pnum, []).append(h_text)

    # Check for explicit Table of Contents page(s)
    toc_line_re = re.compile(
        r"^\s*(?:•\s*)?(?P<title>[A-Za-z0-9\u00C0-\u017F][^\n]{2,90}?)"
        r"(?:\s*(?:\.\s*){2,}|\s{2,})(?P<pnum>\d{1,4})\s*$"
    )
    parsed_toc_entries: List[Tuple[str, int]] = []
    for pnum, txt in sorted(page_texts.items()):
        has_toc_header = bool(re.search(r"(?:^|\n)\s*(?:#+\s*)?(?:Table of Contents|Contents)\b", txt, re.IGNORECASE))
        matches = list(toc_line_re.finditer(txt))
        if has_toc_header or len(matches) >= 5:
            if has_toc_header:
                _add_toc_entry(toc_lists, pnum, "Table of Contents")
            for m in matches:
                t_title = _clean_toc_heading(m.group("title"))
                t_pg = int(m.group("pnum"))
                if t_title and not t_title.isdigit():
                    parsed_toc_entries.append((t_title, t_pg))

    # Determine printed-page to PDF-page offset if TOC lines were parsed
    offset = 0
    if parsed_toc_entries:
        offsets: List[int] = []
        for t_title, t_pg in parsed_toc_entries:
            norm_t = re.sub(r"[^a-z0-9]+", "", t_title.lower())
            if len(norm_t) < 4:
                continue
            for pnum, h_list in page_headings.items():
                for h in h_list:
                    norm_h = re.sub(r"[^a-z0-9]+", "", h.lower())
                    if norm_t == norm_h or (len(norm_t) >= 6 and (norm_t in norm_h or norm_h in norm_t)):
                        offsets.append(pnum - t_pg)
                        break
        if offsets:
            # Mode of detected offsets
            offset = max(set(offsets), key=offsets.count)

        for t_title, t_pg in parsed_toc_entries:
            target_pg = t_pg + offset
            # Also check if an exact heading match exists on a known page
            matched_pg = None
            norm_t = re.sub(r"[^a-z0-9]+", "", t_title.lower())
            for pnum, h_list in page_headings.items():
                for h in h_list:
                    norm_h = re.sub(r"[^a-z0-9]+", "", h.lower())
                    if norm_t and (norm_t == norm_h or (len(norm_t) >= 6 and (norm_t in norm_h or norm_h in norm_t))):
                        matched_pg = pnum
                        break
                if matched_pg is not None:
                    break
            final_pg = matched_pg if matched_pg is not None else target_pg
            if final_pg in page_texts:
                _add_toc_entry(toc_lists, final_pg, t_title)

    # Add page headings for pages (when not already covered or when headings are primary structure)
    for pnum, h_list in sorted(page_headings.items()):
        for h in h_list:
            # Skip repetitive running headers or generic callouts
            if h.upper() in ("DID YOU KNOW?", "EXAMPLE", "REMEMBER", "ROLE MODEL", "CASE STUDY"):
                continue
            _add_toc_entry(toc_lists, pnum, h)

    return toc_lists


def extract_toc_mapping(
    input_path: Path,
    md_dir: Optional[Path] = None,
    pdf_path: Optional[Path] = None,
    toc_file: Optional[Path] = None,
) -> Dict[int, str]:
    """
    Build a mapping of {page_number: 'Title 1 / Title 2'} from available TOC sources:
    1. Explicit toc.json file (if provided or present in input_path / md_dir).
    2. Companion PDF <outline> bookmarks via pdftohtml -xml.
    3. Markdown/Text TOC page parsing + structural page headings.
    """
    input_p = Path(input_path).resolve()
    if md_dir is None:
        md_dir = find_companion_markdown_dir(input_p)

    toc_lists: Dict[int, List[str]] = {}

    # 1. Check explicit toc.json
    toc_candidates = []
    if toc_file:
        toc_candidates.append(Path(toc_file))
    if input_p.is_dir():
        toc_candidates.append(input_p / "toc.json")
    if md_dir and md_dir.is_dir():
        toc_candidates.append(md_dir / "toc.json")

    for cand in toc_candidates:
        if cand.is_file():
            try:
                data = json.loads(cand.read_text(encoding="utf-8"))
                if isinstance(data, dict):
                    for k, v in data.items():
                        m_num = re.search(r"\d+", str(k))
                        if not m_num:
                            continue
                        pnum = int(m_num.group(0))
                        if isinstance(v, list):
                            for item in v:
                                _add_toc_entry(toc_lists, pnum, str(item))
                        elif isinstance(v, str) and v.strip():
                            for part in re.split(r"\s+/\s+", v.strip()):
                                _add_toc_entry(toc_lists, pnum, part)
                elif isinstance(data, list):
                    for entry in data:
                        if isinstance(entry, dict) and "page" in entry and "title" in entry:
                            _add_toc_entry(toc_lists, int(entry["page"]), str(entry["title"]))
                if toc_lists:
                    return {pg: " / ".join(titles) for pg, titles in sorted(toc_lists.items()) if titles}
            except Exception as e:
                logger.warning("Failed to parse TOC file %s: %s", cand, e)

    # 2. Check PDF outline if available
    if pdf_path is None:
        pdf_path = find_companion_pdf(md_dir or input_p)
    if pdf_path and pdf_path.is_file():
        pdf_toc = _extract_pdf_outline_toc(pdf_path)
        for pg, titles in pdf_toc.items():
            for t in titles:
                _add_toc_entry(toc_lists, pg, t)

    # 3. If no PDF outline entries were found, extract from Markdown/text pages
    if not toc_lists:
        scan_dir = md_dir if (md_dir and md_dir.is_dir()) else input_p
        if scan_dir.is_dir():
            doc_files = [
                f for f in scan_dir.iterdir()
                if f.is_file() and f.suffix.lower() in SUPPORTED_EXTENSIONS
            ]
            doc_files.sort(key=natural_sort_key)
        elif scan_dir.is_file():
            doc_files = [scan_dir]
        else:
            doc_files = []

        if doc_files:
            md_toc = _extract_markdown_toc_and_headings(doc_files)
            for pg, titles in md_toc.items():
                for t in titles:
                    _add_toc_entry(toc_lists, pg, t)

    return {pg: " / ".join(titles) for pg, titles in sorted(toc_lists.items()) if titles}


class LaTeXProcessor:
    """
    Extracts LaTeX formulas from Markdown, protects them during Markdown-to-HTML conversion,
    and transforms them into W3C MathML using latex2mathml (for visual HTML) and spoken text
    via md_tts (for TTS synthesis).
    """

    def __init__(self):
        # token -> (sanitized_latex, raw_latex, display_mode)
        self.math_registry: Dict[str, Tuple[str, str, str]] = {}
        self.counter = 0

    def reset(self):
        self.math_registry.clear()
        self.counter = 0

    def _sanitize_latex(self, formula: str) -> str:
        s = formula.strip()
        s = re.sub(r"\\label\{[^}]*\}", "", s)
        s = re.sub(r"\\(?:notag|nonumber)\b", "", s)
        s = re.sub(r"\\\\\s*$", "", s)
        s = re.sub(r"^\\begin\{equation\*?\}([\s\S]*)\\end\{equation\*?\}$", r"\1", s).strip()
        s = re.sub(r"\\bm\b", r"\\mathbf", s)
        return s

    def protect_math_blocks(self, text: str) -> str:
        """Replaces LaTeX display and inline math with unique placeholder tokens before Markdown parsing."""
        # 0. MyST math directives: ```{math} ... ``` or ```{amsmath} ... ```
        def repl_myst_math(match):
            raw = match.group(1).strip()
            lines = [
                l for l in raw.splitlines()
                if not l.strip().startswith(":") and not l.strip().startswith("---")
            ]
            cleaned = "\n".join(lines).strip()
            token = f"MINERUMATHBLOCKTOKEN{self.counter:08d}XYZ"
            self.counter += 1
            self.math_registry[token] = (self._sanitize_latex(cleaned), cleaned, "block")
            return f"\n\n{token}\n\n"

        text = re.sub(r"^\s*```+\{(?:a?ms)?math\}(.*?)\n\s*```+\s*$", repl_myst_math, text, flags=re.DOTALL | re.MULTILINE)

        # 1. LaTeX display environments
        def repl_env(match):
            raw = match.group(0)
            token = f"MINERUMATHBLOCKTOKEN{self.counter:08d}XYZ"
            self.counter += 1
            self.math_registry[token] = (self._sanitize_latex(raw), raw, "block")
            return f"\n\n{token}\n\n"

        env_pattern = (
            r"\\begin\{(?:align\*?|alignat\*?|gather\*?|multline\*?|eqnarray\*?|cases)\}"
            r"[\s\S]*?"
            r"\\end\{(?:align\*?|alignat\*?|gather\*?|multline\*?|eqnarray\*?|cases)\}"
        )
        text = re.sub(env_pattern, repl_env, text)

        # 2. Block math: $$ ... $$
        def repl_block_dollar(match):
            raw = match.group(1)
            token = f"MINERUMATHBLOCKTOKEN{self.counter:08d}XYZ"
            self.counter += 1
            self.math_registry[token] = (self._sanitize_latex(raw), raw, "block")
            return f"\n\n{token}\n\n"

        text = re.sub(r"\$\$\s*([\s\S]*?)\s*\$\$", repl_block_dollar, text)

        # 3. Block math: \[ ... \]
        def repl_block_bracket(match):
            raw = match.group(1)
            token = f"MINERUMATHBLOCKTOKEN{self.counter:08d}XYZ"
            self.counter += 1
            self.math_registry[token] = (self._sanitize_latex(raw), raw, "block")
            return f"\n\n{token}\n\n"

        text = re.sub(r"\\\[\s*([\s\S]*?)\s*\\\]", repl_block_bracket, text)

        # 4. Inline math: \( ... \)
        def repl_inline_paren(match):
            raw = match.group(1)
            token = f"MINERUMATHINLINETOKEN{self.counter:08d}XYZ"
            self.counter += 1
            self.math_registry[token] = (self._sanitize_latex(raw), raw, "inline")
            return token

        text = re.sub(r"\\\(\s*([\s\S]*?)\s*\\\)", repl_inline_paren, text)

        # 5. Inline math: $ ... $
        def repl_inline_dollar(match):
            raw = match.group(1)
            token = f"MINERUMATHINLINETOKEN{self.counter:08d}XYZ"
            self.counter += 1
            self.math_registry[token] = (self._sanitize_latex(raw), raw, "inline")
            return token

        text = re.sub(r"(?<![\$\\])\$(?!\$)([^\$\n]+?)(?<!\\)\$(?!\d)", repl_inline_dollar, text)
        return text

    def render_token_to_mathml(self, token: str) -> Tuple[str, bool]:
        """Render a single math token into visual HTML/MathML and return (html_str, is_mathml)."""
        if token not in self.math_registry:
            return "", False
        sanitized_latex, raw_latex, display_mode = self.math_registry[token]
        if not sanitized_latex.strip():
            return "", False
        try:
            mathml = latex2mathml.converter.convert(sanitized_latex, display=display_mode)
            if display_mode == "block":
                return mathml, True
            return f'<span class="math-inline">{mathml}</span>', True
        except Exception as ex:
            logger.debug("Fallback for LaTeX formula '%s': %s", raw_latex, ex)
            escaped = html.escape(raw_latex.strip())
            if display_mode == "block":
                return f'<code class="math-fallback">$${escaped}$$</code>', False
            return f'<span class="math-inline"><code class="math-fallback">${escaped}$</code></span>', False

    def restore_tokens_in_visual_html(self, html_fragment: str) -> Tuple[str, bool]:
        """Replace all math tokens in an HTML fragment with visual MathML."""
        has_mathml = False
        result = html_fragment
        for token in list(self.math_registry.keys()):
            if token in result:
                rendered, is_m = self.render_token_to_mathml(token)
                if is_m:
                    has_mathml = True
                result = result.replace(token, rendered)
        return result, has_mathml

    def restore_tokens_for_tts(self, fragment: str) -> str:
        """Replace all math tokens in a fragment with LaTeX delimiters so md_tts verbalizes them."""
        result = fragment
        for token, (_sanitized, raw_latex, display_mode) in self.math_registry.items():
            if token in result:
                if display_mode == "block":
                    result = result.replace(token, f" $${raw_latex}$$ ")
                else:
                    result = result.replace(token, f" ${raw_latex}$ ")
        return result


def preprocess_text(text: str, is_plain_text: bool = False) -> str:
    """
    Normalizes line endings, cleans OCR soft-hyphens and MyST roles/directives,
    and prepares text for Markdown-to-XHTML conversion.
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # Strip YAML frontmatter and HTML comments
    text = re.sub(r"^---\s*\n.*?\n---\s*\n", "", text, flags=re.DOTALL)
    text = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    # Soft-hyphen de-hyphenation across OCR line breaks
    text = re.sub(r"(\b[a-zA-Z]{2,})-\s*\n\s*([a-zA-Z]{2,}\b)", r"\1\2", text)
    # Clean OCR sub/sup letter artifacts e.g. <sub>p</sub>lanar -> planar
    text = re.sub(r"<(?:sub|sup)>([a-zA-Z,;'\"]+)</(?:sub|sup)>", r"\1", text)

    if not is_plain_text:
        return text

    lines = text.split("\n")
    processed_lines: List[str] = []
    in_fence = False

    for line in lines:
        stripped = line.strip()
        if stripped.startswith("```") or stripped.startswith("~~~"):
            in_fence = not in_fence
            processed_lines.append(line)
            continue

        if not in_fence and line.startswith(("    ", "\t", "  ", "   ")):
            processed_lines.append(line.lstrip())
        else:
            processed_lines.append(line)

    return "\n".join(processed_lines)


