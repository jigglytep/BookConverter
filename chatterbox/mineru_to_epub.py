def verbalize_for_tts(raw_fragment: str, md_opts=None, md_stats: Optional[dict] = None) -> str:
    """Convert a Markdown/HTML fragment (with LaTeX math, numbers, tables, units) into spoken TTS text."""
    if md_tts is not None:
        if md_opts is None:
            md_opts = _default_md_tts_opts()
        if md_stats is None:
            md_stats = {"equations": 0, "converted": 0, "errors": 0}
        try:
            spoken = md_tts.process(raw_fragment, md_opts, md_stats).strip()
            spoken = re.sub(r"\s+", " ", spoken).strip()
            return spoken
        except Exception as e:
            logger.debug("md_tts fallback on fragment: %s", e)

    # Fallback basic cleanup if md_tts is unavailable
    txt = re.sub(r"<[^>]+>", " ", raw_fragment)
    txt = html.unescape(txt)
    txt = re.sub(r"\s+", " ", txt).strip()
    return txt


# Protect abbreviations before sentence splitting so periods in "e.g.", "Mr.", "Fig. 1" don't split sentences
_ABBREV_PROTECT_RE = re.compile(
    r"\b(?:e\.g\.|i\.e\.|et al\.|etc\.|vs\.|approx\.|dept\.|Fig\.|Figs\.|Tab\.|Tabs\.|Ch\.|Sec\.|pp\.|p\.|Dr\.|Prof\.|Mr\.|Mrs\.|Ms\.|[A-Z]\.)",
    re.IGNORECASE,
)


def _split_balanced_html_sentences(inner_html: str, max_words: int = 24, math_processor: Optional[LaTeXProcessor] = None, md_opts=None, md_stats: Optional[dict] = None) -> List[Tuple[str, str]]:
    """
    Splits an inline HTML string (from inside <p>, <li>, <h1..h6>) into balanced
    (visual_html_template, spoken_text) chunks of at most `max_words` spoken words.
    Never splits inside an HTML tag (<...>) or inside an unclosed inline element (<em>, <strong>, <code>, <a>).
    Prioritizes 1 sentence per chunk (>= 6 words) so EPUB3 SMIL read-along highlighting tracks sentence-by-sentence.
    """
    s = inner_html.strip()
    if not s:
        return []

    # Find top-level (tag_depth == 0, outside <...>) split positions
    void_tags = {"br", "img", "hr", "input", "meta", "link"}

    def _find_balanced_splits(text: str, delimiter_chars: str) -> List[str]:
        parts: List[str] = []
        tag_depth = 0
        in_tag = False
        last_idx = 0
        n = len(text)
        i = 0

        # Mask abbreviations so their periods aren't treated as sentence terminals
        masked = list(text)
        for m in _ABBREV_PROTECT_RE.finditer(text):
            for k in range(m.start(), m.end()):
                if masked[k] == ".":
                    masked[k] = "\x01"
        masked_str = "".join(masked)

        while i < n:
            ch = text[i]
            if ch == "<":
                in_tag = True
                m_tag = re.match(r"<\s*(/?)\s*([a-zA-Z0-9:_\-]+)([^>]*?)(/?)\s*>", text[i:])
                if m_tag:
                    is_close = bool(m_tag.group(1))
                    tname = m_tag.group(2).lower()
                    is_self = bool(m_tag.group(4)) or (tname in void_tags)
                    if not is_self:
                        if is_close:
                            tag_depth = max(0, tag_depth - 1)
                        else:
                            tag_depth += 1
                    i += m_tag.end()
                    in_tag = False
                    continue
            elif ch == ">":
                in_tag = False

            if not in_tag and tag_depth == 0 and masked_str[i] in delimiter_chars:
                # Consume any trailing closing quotes/parens and whitespace
                j = i + 1
                while j < n and text[j] in ('"', "'", "”", "’", ")", "]"):
                    j += 1
                if j < n and text[j].isspace():
                    while j < n and text[j].isspace():
                        j += 1
                    seg = text[last_idx:j].strip()
                    if seg:
                        parts.append(seg)
                    last_idx = j
                    i = j
                    continue
            i += 1

        tail = text[last_idx:].strip()
        if tail:
            parts.append(tail)
        return parts if parts else [text]

    def _split_long_balanced_segment(seg: str, limit: int) -> List[str]:
        # First try splitting on clause delimiters (, ; : — –)
        clauses = _find_balanced_splits(seg, ",;:\u2014\u2013")
        if len(clauses) > 1:
            grouped: List[str] = []
            curr = ""
            curr_w = 0
            for cl in clauses:
                w = len(re.sub(r"<[^>]+>", " ", cl).split())
                if curr and curr_w + w > limit:
                    grouped.append(curr.strip())
                    curr = cl
                    curr_w = w
                else:
                    curr = (curr + " " + cl).strip() if curr else cl
                    curr_w += w
            if curr:
                grouped.append(curr.strip())
            if all(len(re.sub(r"<[^>]+>", " ", g).split()) <= limit * 1.3 for g in grouped):
                return grouped

        # Otherwise split on top-level whitespace every `limit` words
        words_out: List[str] = []
        tag_depth = 0
        in_tag = False
        word_count = 0
        last_idx = 0
        n = len(seg)
        i = 0
        in_word = False
        while i < n:
            ch = seg[i]
            if ch == "<":
                m_tag = re.match(r"<\s*(/?)\s*([a-zA-Z0-9:_\-]+)([^>]*?)(/?)\s*>", seg[i:])
                if m_tag:
                    is_close = bool(m_tag.group(1))
                    tname = m_tag.group(2).lower()
                    is_self = bool(m_tag.group(4)) or (tname in void_tags)
                    if not is_self:
                        tag_depth = max(0, tag_depth - 1) if is_close else (tag_depth + 1)
                    i += m_tag.end()
                    continue
            if not in_tag:
                if not ch.isspace():
                    if not in_word:
                        in_word = True
                        word_count += 1
                else:
                    in_word = False
                    if tag_depth == 0 and word_count >= limit:
                        j = i
                        while j < n and seg[j].isspace():
                            j += 1
                        chunk_s = seg[last_idx:j].strip()
                        if chunk_s:
                            words_out.append(chunk_s)
                        last_idx = j
                        word_count = 0
                        i = j
                        continue
            i += 1
        rem = seg[last_idx:].strip()
        if rem:
            words_out.append(rem)
        return words_out if words_out else [seg]

    raw_sentences = _find_balanced_splits(s, ".!?")
    expanded_sentences: List[str] = []
    for sent in raw_sentences:
        approx_words = len(re.sub(r"<[^>]+>", " ", sent).split())
        if approx_words > max_words:
            expanded_sentences.extend(_split_long_balanced_segment(sent, max_words))
        else:
            expanded_sentences.append(sent)

    # Keep sentences >= min_standalone_words as individual read-along spans; merge tiny fragments (< min_standalone_words)
    min_standalone_words = getattr(config, "MIN_PHRASE_WORDS", 4) if config else 4
    pause_delim = getattr(config, "PAUSE_DELIMITER", " - ") if config else " - "
    grouped_chunks: List[Tuple[str, str]] = []
    curr_html_parts: List[str] = []
    curr_spoken_parts: List[str] = []
    curr_words = 0

    def _join_spoken_parts(parts: List[str]) -> str:
        if not parts:
            return ""
        if len(parts) == 1:
            return parts[0]
        # If any part was a micro-phrase (< min_standalone_words), join with cadence pause delimiter
        has_micro = any(len(p.split()) < min_standalone_words for p in parts)
        sep = pause_delim if has_micro else " "
        return sep.join(parts)

    for sent_html in expanded_sentences:
        tts_input = math_processor.restore_tokens_for_tts(sent_html) if math_processor else sent_html
        spoken = verbalize_for_tts(tts_input, md_opts=md_opts, md_stats=md_stats)
        # Ensure spoken text has actual pronounceable characters
        if not re.search(r"[a-zA-Z0-9]", spoken):
            # Attach non-spoken punctuation/markup to current html part if any
            if curr_html_parts:
                curr_html_parts[-1] = curr_html_parts[-1] + " " + sent_html
            elif grouped_chunks:
                prev_h, prev_s = grouped_chunks[-1]
                grouped_chunks[-1] = (prev_h + " " + sent_html, prev_s)
            continue

        s_words = len(spoken.split())
        if curr_html_parts and (curr_words < min_standalone_words or s_words < min_standalone_words) and (curr_words + s_words <= max_words):
            curr_html_parts.append(sent_html)
            curr_spoken_parts.append(spoken)
            curr_words += s_words
        else:
            if curr_html_parts:
                grouped_chunks.append((" ".join(curr_html_parts), _join_spoken_parts(curr_spoken_parts)))
            curr_html_parts = [sent_html]
            curr_spoken_parts = [spoken]
            curr_words = s_words

        if curr_words >= min_standalone_words:
            grouped_chunks.append((" ".join(curr_html_parts), _join_spoken_parts(curr_spoken_parts)))
            curr_html_parts = []
            curr_spoken_parts = []
            curr_words = 0

    if curr_html_parts:
        tail_spoken = _join_spoken_parts(curr_spoken_parts)
        if grouped_chunks and curr_words < min_standalone_words and (len(grouped_chunks[-1][1].split()) + curr_words <= max_words + 4):
            prev_h, prev_s = grouped_chunks[-1]
            sep = pause_delim if (curr_words < min_standalone_words or len(prev_s.split()) < min_standalone_words) else " "
            grouped_chunks[-1] = (prev_h + " " + " ".join(curr_html_parts), prev_s + sep + tail_spoken)
        else:
            grouped_chunks.append((" ".join(curr_html_parts), tail_spoken))

    return grouped_chunks


def _resolve_and_register_images(
    soup: BeautifulSoup,
    base_dir: Path,
    image_registry: Dict[str, Tuple[str, str, bytes]],
) -> None:
    """
    Finds all <img> tags in `soup`, resolves local image files relative to `base_dir`,
    registers them in `image_registry` (keyed by resolved path -> (uid, epub_rel_path, bytes)),
    and rewrites `img['src']` to `../images/<filename>` relative to `OEBPS/text/page_{num}.xhtml`.
    """
    for img in soup.find_all("img"):
        src = img.get("src")
        if not src or src.startswith(("http://", "https://", "data:")):
            continue
        clean_src = unquote(src.split("?")[0].split("#")[0])
        img_path = (base_dir / clean_src).resolve()
        if not img_path.exists():
            cand1 = (base_dir / Path(clean_src).name).resolve()
            cand2 = (base_dir / "images" / Path(clean_src).name).resolve()
            if cand1.exists():
                img_path = cand1
            elif cand2.exists():
                img_path = cand2
            else:
                logger.warning("Image file not found: %s (referenced as %s)", img_path, src)
                continue

        resolved_key = str(img_path)
        if resolved_key in image_registry:
            _uid, epub_img_rel, _mime, _data = image_registry[resolved_key]
        else:
            mime_type, _ = mimetypes.guess_type(img_path.name)
            if not mime_type:
                ext = img_path.suffix.lower()
                mime_map = {
                    ".png": "image/png",
                    ".jpg": "image/jpeg",
                    ".jpeg": "image/jpeg",
                    ".gif": "image/gif",
                    ".svg": "image/svg+xml",
                    ".webp": "image/webp",
                }
                mime_type = mime_map.get(ext, "image/png")
            try:
                img_data = img_path.read_bytes()
            except Exception as e:
                logger.warning("Failed to read image %s: %s", img_path, e)
                continue

            img_idx = len(image_registry) + 1
            safe_name = re.sub(r"[^a-zA-Z0-9_.\-]", "_", img_path.name)
            epub_img_rel = f"images/img_{img_idx:04d}_{safe_name}"
            uid = f"img_{img_idx:04d}"
            image_registry[resolved_key] = (uid, epub_img_rel, mime_type, img_data)

        # Since XHTML files live in OEBPS/text/page_{num}.xhtml, relative path to OEBPS/images/... is ../images/...
        img["src"] = f"../{epub_img_rel}"


def prepare_page_dom_and_chunks(
    page_num: int,
    chapter_title: str,
    raw_markdown_or_text: str,
    base_dir: Path,
    image_registry: Dict[str, Tuple[str, str, str, bytes]],
    is_plain_text: bool = False,
    language: str = "en",
    chunk_size_words: int = 50,
    md_opts=None,
    md_stats: Optional[dict] = None,
    pad_width: int = 4,
    allow_empty_chunks: bool = False,
) -> PageDOMResult:
    """
    Converts a single page's Markdown or plain text into an EPUB3 XHTML document
    (`OEBPS/text/page_{num}.xhtml`) with every synthesized speech chunk wrapped in
    `<span id="p{page_num:03d}_s{seq:04d}">...</span>`, keeping visual HTML/MathML
    inside the `<span>` while generating the verbalized spoken text for TTS.
    """
    if md_opts is None:
        md_opts = _default_md_tts_opts()
    if md_stats is None:
        md_stats = {"equations": 0, "converted": 0, "errors": 0}

    num_str = format_page_num_str(page_num, pad_width=pad_width)
    span_page_prefix = f"p{page_num:03d}"

    cleaned_md = preprocess_text(raw_markdown_or_text, is_plain_text=is_plain_text)
    math_processor = LaTeXProcessor()
    protected_md = math_processor.protect_math_blocks(cleaned_md)

    md_extensions = [
        "tables",
        "fenced_code",
        "footnotes",
        "attr_list",
        "def_list",
        "sane_lists",
    ]
    html_body = markdown.markdown(protected_md, extensions=md_extensions)
    soup = BeautifulSoup(html_body, "html.parser")

    # Resolve images to ../images/...
    _resolve_and_register_images(soup, base_dir, image_registry)

    chunks: List[SpeechChunk] = []
    seq_counter = 0
    page_has_mathml = False

    def _next_chunk_id() -> str:
        nonlocal seq_counter
        seq_counter += 1
        return f"{span_page_prefix}_s{seq_counter:04d}"

    CONTAINER_TAGS = {"div", "section", "article", "blockquote", "ul", "ol", "dl", "figure", "tbody", "thead", "tr"}
    LEAF_BLOCK_TAGS = {"p", "h1", "h2", "h3", "h4", "h5", "h6", "li", "dt", "dd", "figcaption"}

    def _process_node(node: Tag) -> None:
        nonlocal page_has_mathml

        for child in list(node.children):
            if isinstance(child, NavigableString):
                raw_s = str(child).strip()
                if not raw_s:
                    continue
                # Bare text inside container
                tts_in = math_processor.restore_tokens_for_tts(raw_s)
                spoken = verbalize_for_tts(tts_in, md_opts=md_opts, md_stats=md_stats)
                if re.search(r"[a-zA-Z0-9]", spoken):
                    cid = _next_chunk_id()
                    vis_html, has_m = math_processor.restore_tokens_in_visual_html(html.escape(raw_s))
                    if has_m:
                        page_has_mathml = True
                    chunks.append(SpeechChunk(cid, page_num, seq_counter, spoken, vis_html))
                    span_soup = BeautifulSoup(f'<span id="{cid}">{vis_html}</span>', "html.parser")
                    child.replace_with(span_soup)
                continue

            if not isinstance(child, Tag):
                continue

            tname = child.name.lower()

            # 1. Code blocks (<pre>): keep visually, only speak if md_opts.code != 'drop'
            if tname == "pre":
                if getattr(md_opts, "code", "drop") != "drop":
                    code_txt = child.get_text()
                    spoken = verbalize_for_tts(f"```\n{code_txt}\n```", md_opts=md_opts, md_stats=md_stats)
                    if re.search(r"[a-zA-Z0-9]", spoken):
                        cid = _next_chunk_id()
                        inner = child.decode_contents()
                        chunks.append(SpeechChunk(cid, page_num, seq_counter, spoken, inner))
                        child.clear()
                        child.append(BeautifulSoup(f'<span id="{cid}">{inner}</span>', "html.parser"))
                continue

            # 2. Tables (<table>): keep full HTML table visually, speak table note ("See table ...")
            if tname == "table":
                if getattr(md_opts, "tables", "note") != "drop":
                    spoken = verbalize_for_tts(str(child), md_opts=md_opts, md_stats=md_stats)
                    if re.search(r"[a-zA-Z0-9]", spoken):
                        cid = _next_chunk_id()
                        vis_table, has_m = math_processor.restore_tokens_in_visual_html(str(child))
                        if has_m:
                            page_has_mathml = True
                        chunks.append(SpeechChunk(cid, page_num, seq_counter, spoken, vis_table))
                        wrapped_table = BeautifulSoup(
                            f'<div class="table-container"><span id="{cid}">{vis_table}</span></div>',
                            "html.parser",
                        )
                        child.replace_with(wrapped_table)
                        continue
                vis_table, has_m = math_processor.restore_tokens_in_visual_html(str(child))
                if has_m:
                    page_has_mathml = True
                child.replace_with(BeautifulSoup(vis_table, "html.parser"))
                continue

            # 3. Leaf block tags (<p>, <h1..h6>, <li>, <dt>, <dd>, <figcaption>)
            if tname in LEAF_BLOCK_TAGS:
                # If a <li> contains nested <ul>/<ol>/<p>, process inline prefix and recurse on block children
                has_nested_blocks = any(
                    isinstance(c, Tag) and c.name.lower() in (CONTAINER_TAGS | LEAF_BLOCK_TAGS | {"table", "pre"})
                    for c in child.children
                )
                if has_nested_blocks:
                    _process_node(child)
                    continue

                inner_html = child.decode_contents().strip()
                if not inner_html:
                    continue

                # Check if this <p> is a standalone display math block token
                if tname == "p" and inner_html in math_processor.math_registry:
                    _san, raw_latex, disp_mode = math_processor.math_registry[inner_html]
                    if disp_mode == "block":
                        rendered_math, has_m = math_processor.render_token_to_mathml(inner_html)
                        if has_m:
                            page_has_mathml = True
                        spoken = verbalize_for_tts(f"$${raw_latex}$$", md_opts=md_opts, md_stats=md_stats)
                        if re.search(r"[a-zA-Z0-9]", spoken):
                            cid = _next_chunk_id()
                            chunks.append(SpeechChunk(cid, page_num, seq_counter, spoken, rendered_math))
                            math_div = BeautifulSoup(
                                f'<div class="math-block"><span id="{cid}">{rendered_math}</span></div>',
                                "html.parser",
                            )
                        else:
                            math_div = BeautifulSoup(f'<div class="math-block">{rendered_math}</div>', "html.parser")
                        child.replace_with(math_div)
                        continue

                # Separate any <img> tags inside the block so images stay intact
                imgs = child.find_all("img")
                img_html_list = [str(im) for im in imgs]
                img_alt_list = [im.get("alt", "").strip() for im in imgs if im.get("alt", "").strip()]
                for im in imgs:
                    im.decompose()

                remaining_inner = child.decode_contents().strip()
                new_children_html: List[str] = []
                if img_html_list:
                    new_children_html.extend(img_html_list)

                if remaining_inner:
                    # For headings and list items, ensure TTS spoken text ends with sentence punctuation
                    is_heading_or_list = tname in ("h1", "h2", "h3", "h4", "h5", "h6", "li", "dt")
                    sentence_pairs = _split_balanced_html_sentences(
                        remaining_inner,
                        max_words=chunk_size_words,
                        math_processor=math_processor,
                        md_opts=md_opts,
                        md_stats=md_stats,
                    )
                    for vis_template, spoken in sentence_pairs:
                        if is_heading_or_list and spoken and spoken[-1] not in ".!?:;":
                            spoken += "."
                        vis_html, has_m = math_processor.restore_tokens_in_visual_html(vis_template)
                        if has_m:
                            page_has_mathml = True
                        cid = _next_chunk_id()
                        chunks.append(SpeechChunk(cid, page_num, seq_counter, spoken, vis_html))
                        new_children_html.append(f'<span id="{cid}">{vis_html}</span>')
                elif img_alt_list and getattr(md_opts, "images", "caption") != "drop":
                    # Image-only paragraph with alt text
                    for alt_text in img_alt_list:
                        spoken = verbalize_for_tts(f"Figure: {alt_text}.", md_opts=md_opts, md_stats=md_stats)
                        if re.search(r"[a-zA-Z0-9]", spoken):
                            cid = _next_chunk_id()
                            esc_alt = html.escape(alt_text)
                            chunks.append(SpeechChunk(cid, page_num, seq_counter, spoken, esc_alt))
                            new_children_html.append(f'<span id="{cid}" class="figcaption">{esc_alt}</span>')

                if new_children_html:
                    child.clear()
                    joined_inner = " ".join(new_children_html)
                    child.append(BeautifulSoup(joined_inner, "html.parser"))
                continue

            # 4. Container tags (<blockquote>, <ul>, <ol>, <div>, <figure>, etc.)
            if tname in CONTAINER_TAGS:
                _process_node(child)
                continue

            # Any other tag: restore math tokens if present
            raw_c = str(child)
            vis_c, has_m = math_processor.restore_tokens_in_visual_html(raw_c)
            if has_m:
                page_has_mathml = True
            if vis_c != raw_c:
                child.replace_with(BeautifulSoup(vis_c, "html.parser"))

    _process_node(soup)

    # Intra-page sliding window pass across chunks:
    # Ensure no speech chunk is left with fewer than min_phrase_words (< 4 words)
    min_phrase_words = getattr(config, "MIN_PHRASE_WORDS", 4) if config else 4
    pause_delim = getattr(config, "PAUSE_DELIMITER", " - ") if config else " - "

    if len(chunks) > 1:
        merged_chunks: List[SpeechChunk] = []
        for chk in chunks:
            chk_words = len(chk.spoken_text.split())
            if not merged_chunks:
                merged_chunks.append(chk)
                continue
            prev = merged_chunks[-1]
            prev_words = len(prev.spoken_text.split())
            if chk_words < min_phrase_words or prev_words < min_phrase_words:
                # Merge into previous chunk
                new_spoken = f"{prev.spoken_text.strip()}{pause_delim}{chk.spoken_text.strip()}"
                new_vis = f"{prev.visual_html} {chk.visual_html}"
                merged_chunks[-1] = SpeechChunk(
                    chunk_id=prev.chunk_id,
                    page_num=prev.page_num,
                    seq_idx=prev.seq_idx,
                    spoken_text=new_spoken,
                    visual_html=new_vis,
                )
                # In the soup HTML, update the absorbed chunk's span id to prev.chunk_id
                target_span = soup.find(id=chk.chunk_id)
                if target_span:
                    target_span["id"] = prev.chunk_id
            else:
                merged_chunks.append(chk)
        chunks = merged_chunks

    # Ensure every page has at least one spoken chunk so SMIL and per-page MP3 are always valid (unless empty chunks explicitly allowed e.g. for merged micro-pages)
    if not chunks and not allow_empty_chunks:
        cid = _next_chunk_id()
        spoken_fallback = verbalize_for_tts(f"{chapter_title}.", md_opts=md_opts, md_stats=md_stats)
        if not spoken_fallback:
            spoken_fallback = f"Page {page_num}."
        esc_title = html.escape(chapter_title)
        chunks.append(SpeechChunk(cid, page_num, seq_counter, spoken_fallback, esc_title))
        fallback_p = BeautifulSoup(f'<p class="page-fallback"><span id="{cid}">{esc_title}</span></p>', "html.parser")
        soup.append(fallback_p)

    final_body_html = str(soup)

    xhtml_content = f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="{language}" lang="{language}">
<head>
    <meta charset="utf-8" />
    <title>{html.escape(chapter_title)}</title>
    <link rel="stylesheet" type="text/css" href="../styles/ebook.css" />
</head>
<body>
    <section epub:type="bodymatter chapter" id="sec_page_{num_str}">
        <span epub:type="pagebreak" id="page_{page_num}" title="{html.escape(chapter_title)}" />
{final_body_html}
    </section>
</body>
</html>"""

    return PageDOMResult(
        page_num=page_num,
        num_str=num_str,
        chapter_title=chapter_title,
        xhtml_filename=f"text/page_{num_str}.xhtml",
        smil_filename=f"smil/page_{num_str}.smil",
        audio_filename=f"audio/page_{num_str}.mp3",
        xhtml_content=xhtml_content,
        has_mathml=page_has_mathml,
        chunks=chunks,
    )


def generate_smil_xml(num_str: str, par_entries: List[Tuple[str, str, str]]) -> str:
    """
    Generate valid SMIL 3.0 XML for `OEBPS/smil/page_{num}.smil` mapping
    `<text src="../text/page_{num}.xhtml#{chunk_id}"/>` to
    `<audio src="../audio/page_{num}.mp3" clipBegin="HH:MM:SS.mmm" clipEnd="HH:MM:SS.mmm"/>`.
    """
    par_blocks: List[str] = []
    for idx, (chunk_id, clip_begin, clip_end) in enumerate(par_entries, 1):
        par_blocks.append(
            f'      <par id="par_{idx:04d}">\n'
            f'        <text src="../text/page_{num_str}.xhtml#{chunk_id}"/>\n'
            f'        <audio src="../audio/page_{num_str}.mp3" clipBegin="{clip_begin}" clipEnd="{clip_end}"/>\n'
            f'      </par>'
        )
    pars_str = "\n".join(par_blocks)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<smil xmlns="http://www.w3.org/ns/SMIL" xmlns:epub="http://www.idpf.org/2007/ops" version="3.0">
  <body>
    <seq id="seq_page_{num_str}" epub:textref="../text/page_{num_str}.xhtml" epub:type="bodymatter chapter">
{pars_str}
    </seq>
  </body>
</smil>
"""


def encode_page_pcm_to_mp3(
    pcm_int16: np.ndarray,
    sample_rate: int,
    mp3_path: Path,
    bitrate: str = "128k",
) -> None:
    """
    Encode concatenated raw 16-bit PCM audio array for a single page into Constant Bitrate (CBR) MP3
    (`-codec:a libmp3lame -b:a 128k -ac 1`) once per page/chapter.
    """
    mp3_path.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        "ffmpeg",
        "-y",
        "-f", "s16le",
        "-ar", str(sample_rate),
        "-ac", "1",
        "-i", "pipe:0",
        "-codec:a", "libmp3lame",
        "-b:a", bitrate,
        "-ac", "1",
        str(mp3_path),
    ]
    res = subprocess.run(cmd, input=pcm_int16.tobytes(), capture_output=True)
    if res.returncode != 0:
        err = res.stderr.decode("utf-8", errors="replace")[-1500:]
        raise RuntimeError(f"ffmpeg failed encoding {mp3_path.name}: {err}")


def assemble_page_audio_and_smil(
    page_dom: PageDOMResult,
    chunk_wav_paths: List[Path],
    out_mp3_path: Path,
    sample_rate: int = 24000,
    chunk_gap_ms: int = 250,
    book_start_sec: float = 0.0,
    mp3_bitrate: str = "128k",
) -> PageOverlayTiming:
    """
    Reads raw PCM samples for each chunk of a page before lossy encoding, computes sample-accurate
    durations (`len(samples) / sample_rate`), concatenates the raw audio arrays plus inter-sentence
    silence padding in memory, encodes once to CBR MP3 (`OEBPS/audio/page_{num}.mp3`), and generates
    the SMIL 3.0 XML (`OEBPS/smil/page_{num}.smil`).
    """
    sr = sample_rate
    gap_samples_count = int(round(sr * (chunk_gap_ms / 1000.0))) if chunk_gap_ms > 0 else 0
    silence_arr = np.zeros(gap_samples_count, dtype=np.int16)
    silence_duration = len(silence_arr) / float(sr)

    pcm_parts: List[np.ndarray] = []
    par_entries: List[Tuple[str, str, str]] = []
    page_clock = 0.0

    for chunk, wav_path in zip(page_dom.chunks, chunk_wav_paths):
        samples: Optional[np.ndarray] = None
        if wav_path and wav_path.exists() and wav_path.stat().st_size > 44:
            try:
                with wave.open(str(wav_path), "rb") as wf:
                    file_sr = wf.getframerate()
                    nch = wf.getnchannels()
                    sw = wf.getsampwidth()
                    nframes = wf.getnframes()
                    raw_bytes = wf.readframes(nframes)
                if sw == 2:
                    arr = np.frombuffer(raw_bytes, dtype=np.int16)
                    if nch > 1:
                        arr = arr.reshape(-1, nch)[:, 0]
                    samples = arr
                    sr = file_sr
                    if gap_samples_count != int(round(sr * (chunk_gap_ms / 1000.0))):
                        gap_samples_count = int(round(sr * (chunk_gap_ms / 1000.0)))
                        silence_arr = np.zeros(gap_samples_count, dtype=np.int16)
                        silence_duration = len(silence_arr) / float(sr)
            except Exception as e:
                logger.warning("Failed reading WAV chunk %s: %s", wav_path, e)

        if samples is None or len(samples) == 0:
            # Fallback 0.25s silence if a chunk failed synthesis
            samples = np.zeros(max(1, int(sr * 0.25)), dtype=np.int16)

        chunk_duration = len(samples) / float(sr)
        clip_begin_sec = page_clock
        clip_end_sec = page_clock + chunk_duration

        par_entries.append(
            (
                chunk.chunk_id,
                format_smil_timestamp(clip_begin_sec),
                format_smil_timestamp(clip_end_sec),
            )
        )

        pcm_parts.append(samples)
        if gap_samples_count > 0:
            pcm_parts.append(silence_arr)

        # Advance clock by chunk_duration + silence_duration
        page_clock += chunk_duration + silence_duration

    if pcm_parts:
        page_pcm = np.concatenate(pcm_parts)
    else:
        page_pcm = np.zeros(int(sr * 0.5), dtype=np.int16)
        page_clock = len(page_pcm) / float(sr)

    encode_page_pcm_to_mp3(page_pcm, sr, out_mp3_path, bitrate=mp3_bitrate)
    smil_xml = generate_smil_xml(page_dom.num_str, par_entries)

    start_ms = int(round(book_start_sec * 1000.0))
    end_ms = int(round((book_start_sec + page_clock) * 1000.0))

    return PageOverlayTiming(
        page_num=page_dom.page_num,
        num_str=page_dom.num_str,
        chapter_title=page_dom.chapter_title,
        duration_sec=page_clock,
        start_ms=start_ms,
        end_ms=end_ms,
        par_entries=par_entries,
        smil_xml=smil_xml,
        mp3_path=out_mp3_path,
    )


def build_nav_xhtml(
    title: str,
    language: str,
    page_doms: List[PageDOMResult],
) -> str:
    """
    Build EPUB3 `OEBPS/nav.xhtml` containing both `<nav epub:type="toc">` and
    `<nav epub:type="page-list">` using the exact page chapter titles.
    """
    items_html = []
    for p in page_doms:
        esc_title = html.escape(p.chapter_title)
        items_html.append(f'        <li><a href="{p.xhtml_filename}">{esc_title}</a></li>')
    items_joined = "\n".join(items_html)

    return f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="{language}" lang="{language}">
<head>
    <meta charset="utf-8" />
    <title>{html.escape(title)} - Navigation</title>
    <link rel="stylesheet" type="text/css" href="styles/ebook.css" />
</head>
<body>
    <nav epub:type="toc" id="toc">
      <h1>Table of Contents</h1>
      <ol>
{items_joined}
      </ol>
    </nav>
    <nav epub:type="page-list" id="page-list">
      <h1>Pages</h1>
      <ol>
{items_joined}
      </ol>
    </nav>
</body>
</html>
"""


def build_content_opf(
    title: str,
    author: str,
    language: str,
    identifier: str,
    publisher: Optional[str],
    page_doms: List[PageDOMResult],
    page_timings: Optional[Dict[int, PageOverlayTiming]],
    image_registry: Dict[str, Tuple[str, str, str, bytes]],
    cover_item_info: Optional[Tuple[str, str]] = None,
) -> str:
    """
    Build strict EPUB3 `OEBPS/content.opf` with Media Overlay metadata, per-page SMIL
    durations, global book duration, and manifest items.
    """
    modified_utc = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    has_overlays = bool(page_timings)

    meta_lines = [
        f'    <dc:identifier id="BookId">{html.escape(identifier)}</dc:identifier>',
        f'    <dc:title>{html.escape(title)}</dc:title>',
        f'    <dc:language>{html.escape(language)}</dc:language>',
        f'    <dc:creator>{html.escape(author)}</dc:creator>',
    ]
    if publisher:
        meta_lines.append(f'    <dc:publisher>{html.escape(publisher)}</dc:publisher>')
    meta_lines.append(f'    <meta property="dcterms:modified">{modified_utc}</meta>')

    if has_overlays and page_timings:
        meta_lines.append('    <meta property="media:active-class">-epub-media-overlay-active</meta>')
        meta_lines.append('    <meta property="media:playback-active-class">-epub-media-overlay-playing</meta>')
        total_sec = sum(t.duration_sec for t in page_timings.values())
        meta_lines.append(f'    <meta property="media:duration">{format_smil_timestamp(total_sec)}</meta>')
        for p in page_doms:
            t = page_timings.get(p.page_num)
            if t is not None:
                meta_lines.append(
                    f'    <meta property="media:duration" refines="#smil_page_{p.num_str}">'
                    f'{format_smil_timestamp(t.duration_sec)}</meta>'
                )

    manifest_lines = [
        '    <item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>',
        '    <item id="css" href="styles/ebook.css" media-type="text/css"/>',
    ]

    if cover_item_info:
        cov_href, cov_mime = cover_item_info
        manifest_lines.append(
            f'    <item id="cover_img" href="{cov_href}" media-type="{cov_mime}" properties="cover-image"/>'
        )

    for _resolved, (uid, epub_img_rel, mime_type, _data) in image_registry.items():
        manifest_lines.append(
            f'    <item id="{uid}" href="{epub_img_rel}" media-type="{mime_type}"/>'
        )

    spine_lines = []
    for p in page_doms:
        props = ["mathml"] if p.has_mathml else []
        prop_attr = f' properties="{" ".join(props)}"' if props else ""
        has_page_overlay = bool(has_overlays and page_timings and p.page_num in page_timings)
        overlay_attr = f' media-overlay="smil_page_{p.num_str}"' if has_page_overlay else ""

        manifest_lines.append(
            f'    <item id="page_{p.num_str}" href="{p.xhtml_filename}" '
            f'media-type="application/xhtml+xml"{overlay_attr}{prop_attr}/>'
        )
        if has_page_overlay:
            manifest_lines.append(
                f'    <item id="smil_page_{p.num_str}" href="{p.smil_filename}" '
                f'media-type="application/smil+xml"/>'
            )
            manifest_lines.append(
                f'    <item id="audio_page_{p.num_str}" href="{p.audio_filename}" '
                f'media-type="audio/mpeg"/>'
            )
        spine_lines.append(f'    <itemref idref="page_{p.num_str}"/>')

    meta_block = "\n".join(meta_lines)
    manifest_block = "\n".join(manifest_lines)
    spine_block = "\n".join(spine_lines)

    return f"""<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="BookId" prefix="media: http://www.idpf.org/epub/vocab/overlays/#">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
{meta_block}
  </metadata>
  <manifest>
{manifest_block}
  </manifest>
  <spine>
{spine_block}
  </spine>
</package>
"""


def package_epub3(
    output_epub_path: Path,
    title: str,
    author: str,
    language: str,
    identifier: str,
    publisher: Optional[str],
    css_content: str,
    page_doms: List[PageDOMResult],
    page_timings: Optional[Dict[int, PageOverlayTiming]],
    image_registry: Dict[str, Tuple[str, str, str, bytes]],
    cover_image_path: Optional[str] = None,
) -> Path:
    """
    Packages the EPUB3 archive with `mimetype` (`application/epub+zip`) as the first,
    uncompressed (`ZIP_STORED`) file, followed by `META-INF/container.xml` and `OEBPS/`.
    """
    output_epub_path = Path(output_epub_path).resolve()
    output_epub_path.parent.mkdir(parents=True, exist_ok=True)

    container_xml = """<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>
"""

    cover_item_info: Optional[Tuple[str, str]] = None
    cover_bytes: Optional[bytes] = None
    if cover_image_path and Path(cover_image_path).is_file():
        cp = Path(cover_image_path)
        cov_mime, _ = mimetypes.guess_type(cp.name)
        cov_mime = cov_mime or "image/jpeg"
        safe_cov = re.sub(r"[^a-zA-Z0-9_.\-]", "_", cp.name)
        cover_item_info = (f"images/cover_{safe_cov}", cov_mime)
        cover_bytes = cp.read_bytes()

    nav_xhtml = build_nav_xhtml(title=title, language=language, page_doms=page_doms)
    content_opf = build_content_opf(
        title=title,
        author=author,
        language=language,
        identifier=identifier,
        publisher=publisher,
        page_doms=page_doms,
        page_timings=page_timings,
        image_registry=image_registry,
        cover_item_info=cover_item_info,
    )

    with zipfile.ZipFile(output_epub_path, "w") as zf:
        # 1. First entry: uncompressed mimetype
        zf.writestr("mimetype", b"application/epub+zip", compress_type=zipfile.ZIP_STORED)

        # 2. META-INF/container.xml
        zf.writestr("META-INF/container.xml", container_xml.encode("utf-8"), compress_type=zipfile.ZIP_DEFLATED)

        # 3. OEBPS/content.opf, OEBPS/nav.xhtml, OEBPS/styles/ebook.css
        zf.writestr("OEBPS/content.opf", content_opf.encode("utf-8"), compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/nav.xhtml", nav_xhtml.encode("utf-8"), compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/styles/ebook.css", css_content.encode("utf-8"), compress_type=zipfile.ZIP_DEFLATED)

        # 4. Cover image & embedded page images
        if cover_item_info and cover_bytes is not None:
            zf.writestr(f"OEBPS/{cover_item_info[0]}", cover_bytes, compress_type=zipfile.ZIP_DEFLATED)

        for _resolved, (_uid, epub_img_rel, _mime_type, img_data) in image_registry.items():
            zf.writestr(f"OEBPS/{epub_img_rel}", img_data, compress_type=zipfile.ZIP_DEFLATED)

        # 5. Per-page XHTML, SMIL, and MP3 files
        for p in page_doms:
            zf.writestr(f"OEBPS/{p.xhtml_filename}", p.xhtml_content.encode("utf-8"), compress_type=zipfile.ZIP_DEFLATED)
            if page_timings and p.page_num in page_timings:
                t = page_timings[p.page_num]
                zf.writestr(f"OEBPS/{p.smil_filename}", t.smil_xml.encode("utf-8"), compress_type=zipfile.ZIP_DEFLATED)
                if t.mp3_path and t.mp3_path.is_file():
                    zf.write(t.mp3_path, f"OEBPS/{p.audio_filename}", compress_type=zipfile.ZIP_STORED)

    return output_epub_path


def extract_title_from_markdown(text: str, fallback_title: str) -> str:
    """Extracts title from markdown '# Title', metadata 'Title: ...', or fallback."""
    for line in text.splitlines():
        s = line.strip()
        if not s:
            continue
        if s.startswith("# "):
            title = s[2:].strip()
            if title:
                return title
        if s.lower().startswith("title:"):
            title = s[6:].strip()
            if title:
                return title
        if s.startswith("% "):
            title = s[2:].strip()
            if title:
                return title
    return fallback_title


extract_title = extract_title_from_markdown


def gather_page_documents(input_path: Path) -> List[Path]:
    """Gather sorted page document files (.md, .txt) from a file or directory."""
    input_p = Path(input_path).resolve()
    if input_p.is_file():
        return [input_p]
    if input_p.is_dir():
        found = [
            f for f in input_p.iterdir()
            if f.is_file() and f.suffix.lower() in SUPPORTED_EXTENSIONS and f.name.lower() != "toc.json"
        ]
        if not found:
            found = [
                f for f in input_p.rglob("*")
                if f.is_file() and f.suffix.lower() in SUPPORTED_EXTENSIONS and f.name.lower() != "toc.json"
            ]
        found.sort(key=natural_sort_key)
        # Filter out completely blank pages (e.g. '<!-- blank page -->' with no text/images)
        non_empty = []
        for f in found:
            txt = read_file_text(f).strip()
            txt_no_comments = re.sub(r"<!--.*?-->", "", txt, flags=re.DOTALL).strip()
            if len(txt_no_comments) > 0:
                non_empty.append(f)
        return non_empty if non_empty else found
    raise FileNotFoundError(f"Input path not found: {input_path}")


def convert_mineru_to_epub(
    input_path: str,
    output_epub_path: Optional[str] = None,
    title: Optional[str] = None,
    author: str = "MinerU",
    language: str = "en",
    split_level: int = 1,
    cover_image_path: Optional[str] = None,
    custom_css_path: Optional[str] = None,
    identifier: Optional[str] = None,
    publisher: Optional[str] = None,
    chapter_pattern: Optional[str] = None,
    preserve_linebreaks: bool = False,
    chunks_dir: Optional[str] = None,
    toc_file: Optional[str] = None,
    chunk_size_words: int = 50,
    sample_rate: int = 24000,
    chunk_gap_ms: int = 250,
) -> str:
    """
    Main conversion function. Converts a directory of page files (or a single file)
    into a page-structured EPUB3 file with LaTeX MathML support, embedded images,
    `<span id="p{page}_s{chunk}">` DOM wrapping, and (if chunk WAVs / overlay manifest exist)
    synchronized SMIL 3.0 Media Overlays and per-page CBR MP3 audio tracks.
    """
    input_p = Path(input_path).resolve()
    if not input_p.exists():
        raise FileNotFoundError(f"Input path not found: {input_path}")

    doc_files = gather_page_documents(input_p)
    if not doc_files:
        raise FileNotFoundError(f"No supported document files found in: {input_path}")

    base_dir = input_p if input_p.is_dir() else input_p.parent
    book_meta = load_or_extract_book_metadata(input_p)
    first_content = read_file_text(doc_files[0])
    if not title or title == canonical_book_name(input_p):
        title = book_meta.get("title") or extract_title_from_markdown(first_content, canonical_book_name(input_p))
    if (not author or author == "MinerU") and book_meta.get("authors"):
        author = ", ".join(book_meta["authors"])
    if not publisher and book_meta.get("publisher"):
        publisher = book_meta.get("publisher")
    if not cover_image_path and book_meta.get("coverPath") and Path(book_meta["coverPath"]).is_file():
        cover_image_path = str(book_meta["coverPath"])

    if not output_epub_path:
        output_epub_path = str(base_dir / f"{canonical_book_name(input_p)}.epub")

    # Extract TOC mapping for page-based chapter titles
    toc_map = extract_toc_mapping(
        input_p,
        toc_file=Path(toc_file) if toc_file else None,
    )

    css_content = DEFAULT_CSS
    if custom_css_path and Path(custom_css_path).is_file():
        css_content = Path(custom_css_path).read_text(encoding="utf-8")

    image_registry: Dict[str, Tuple[str, str, str, bytes]] = {}
    page_doms: List[PageDOMResult] = []
    md_opts = _default_md_tts_opts()
    md_stats = {"equations": 0, "converted": 0, "errors": 0}

    for idx, doc_file in enumerate(doc_files, 1):
        pnum = extract_page_number(doc_file, idx)
        chap_title = format_page_chapter_title(pnum, toc_map)
        raw_text = read_file_text(doc_file)
        is_plain = doc_file.suffix.lower() in (".txt", ".text")
        pdom = prepare_page_dom_and_chunks(
            page_num=pnum,
            chapter_title=chap_title,
            raw_markdown_or_text=raw_text,
            base_dir=doc_file.parent,
            image_registry=image_registry,
            is_plain_text=is_plain,
            language=language,
            chunk_size_words=chunk_size_words,
            md_opts=md_opts,
            md_stats=md_stats,
        )
        page_doms.append(pdom)

    # Check if chunks_dir with synthesized chunk WAVs is available to build SMIL + MP3 overlays
    resolved_chunks_dir: Optional[Path] = None
    if chunks_dir and Path(chunks_dir).is_dir():
        resolved_chunks_dir = Path(chunks_dir).resolve()
    else:
        bname = canonical_book_name(input_p)
        for cand in (
            SCRIPT_DIR / "chunks" / f"{bname}_txt",
            SCRIPT_DIR / "chunks" / f"{bname}_md",
            SCRIPT_DIR / "chunks" / bname,
        ):
            if cand.is_dir() and any(cand.glob("chunk_*.wav")):
                resolved_chunks_dir = cand
                break

    page_timings: Optional[Dict[int, PageOverlayTiming]] = None
    if resolved_chunks_dir is not None:
        total_expected_chunks = sum(len(p.chunks) for p in page_doms)
        existing_wavs = sorted(resolved_chunks_dir.glob("chunk_*.wav"))
        if len(existing_wavs) >= total_expected_chunks and total_expected_chunks > 0:
            page_timings = {}
            page_audio_dir = resolved_chunks_dir / "page_audio"
            page_audio_dir.mkdir(parents=True, exist_ok=True)
            global_chunk_idx = 1
            book_clock = 0.0
            for pdom in page_doms:
                c_wavs = [
                    resolved_chunks_dir / f"chunk_{global_chunk_idx + j:04d}.wav"
                    for j in range(len(pdom.chunks))
                ]
                global_chunk_idx += len(pdom.chunks)
                mp3_path = page_audio_dir / f"page_{pdom.num_str}.mp3"
                timing = assemble_page_audio_and_smil(
                    page_dom=pdom,
                    chunk_wav_paths=c_wavs,
                    out_mp3_path=mp3_path,
                    sample_rate=sample_rate,
                    chunk_gap_ms=chunk_gap_ms,
                    book_start_sec=book_clock,
                )
                page_timings[pdom.page_num] = timing
                book_clock += timing.duration_sec

    out_path = package_epub3(
        output_epub_path=Path(output_epub_path),
        title=title,
        author=author,
        language=language,
        identifier=identifier or f"urn:uuid:{uuid.uuid4()}",
        publisher=publisher,
        css_content=css_content,
        page_doms=page_doms,
        page_timings=page_timings,
        image_registry=image_registry,
        cover_image_path=cover_image_path,
    )

    logger.info(
        "Successfully generated EPUB3: %s (Pages: %d, Images: %d, Media Overlays: %s)",
        out_path,
        len(page_doms),
        len(image_registry),
        "Yes" if page_timings else "No",
    )
    return str(out_path)


