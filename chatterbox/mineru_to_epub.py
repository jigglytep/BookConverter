"""
mineru_to_epub.py
=================
Converts Markdown (.md) and Text (.txt) page files (generated by MinerU / magic-pdf
or TTS_Script) into synchronized EPUB3 ebooks with SMIL 3.0 Media Overlays
(read-along highlighting) and page-based chapter navigation.

Key Features:
- Page-Based Chapter Structure & Naming Convention:
  - Default chapter title: 'Page {page_number}' (e.g. 'Page 12')
  - TOC Match chapter title: 'Page {page_number}: {title of page in table of contents}'
    (joining multiple headings on the same page with ' / ')
  - Applied consistently across EPUB3 <nav epub:type="toc">, <nav epub:type="page-list">,
    and M4B FFMETADATAFILE [CHAPTER] markers.
- Deterministic Read-Along Highlighting (EPUB3 + SMIL 3.0 Media Overlays):
  - Wraps every synthesized speech chunk in OEBPS/text/page_{num}.xhtml with a sequential
    span ID (e.g. <span id="p012_s0001">...</span>), preserving visual HTML & W3C MathML
    inside the <span> while passing the verbalized/normalized spoken string to TTS.
  - Sample-accurate timing measured directly from raw PCM/WAV samples (len(samples) / sr)
    before lossy encoding, advancing cumulative clipBegin/clipEnd by chunk_duration + silence_duration.
  - Concatenates raw audio arrays + silence padding in memory per page and encodes once per page
    to CBR MP3 (-codec:a libmp3lame -b:a 128k -ac 1) at OEBPS/audio/page_{num}.mp3.
  - Generates OEBPS/smil/page_{num}.smil, OEBPS/content.opf, OEBPS/nav.xhtml, and OEBPS/styles/ebook.css.
"""

