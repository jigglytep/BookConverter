# Default regex patterns for matching standard chapter headings in plain text documents
DEFAULT_CHAPTER_PATTERNS = [
    r"^\s*(?:CHAPTER|Chapter|Part|PART|Section|SECTION|Book|BOOK|Volume|VOLUME|Act|ACT|Scene|SCENE|Appendix|APPENDIX)"
    r"\s+(?:[0-9]+(?:\.[0-9]+)*|[IVXLCDM]+|[A-Z]|One|Two|Three|Four|Five|Six|Seven|Eight|Nine|Ten|"
    r"Eleven|Twelve|Thirteen|Fourteen|Fifteen|Sixteen|Seventeen|Eighteen|Nineteen|Twenty|"
    r"First|Second|Third|Fourth|Fifth|Sixth|Seventh|Eighth|Ninth|Tenth)\b"
    r"(?:\s*[:.\-—]\s*.*|\s+[A-Z].*)?$",
    r"^\s*(?:[IVXLCDM]{1,6}|\d{1,2})\.\s+[A-Z][^\n]{2,80}$",
    r"^\s*(?:PROLOGUE|Prologue|EPILOGUE|Epilogue|PREFACE|Preface|INTRODUCTION|Introduction|"
    r"CONCLUSION|Conclusion|AFTERWORD|Afterword|FOREWORD|Foreword|CONTENTS|Contents|TABLE OF CONTENTS|Table of Contents)"
    r"(?:\s*[:.\-—]\s*.*|\s+[A-Z].*)?$",
]
COMPILED_DEFAULT_CHAPTER_REGEX = re.compile("|".join(f"(?:{p})" for p in DEFAULT_CHAPTER_PATTERNS))


